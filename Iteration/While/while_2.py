
# Here I am going to print all the even numbers between 1 and 20
# For this operation i going to use while loop

number = 1

while number <= 10 :
    if number % 2 == 0 :
        print(number, " is even number")
        number += 1
    else :
        print(number, " is odd number")
        number += 1

print("end !!!")